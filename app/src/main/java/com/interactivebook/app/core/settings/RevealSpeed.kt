package com.interactivebook.app.core.settings

/**
 * Скорость появления сцены (пункт 3 правок): игрок выбирает темп в настройках.
 * INSTANT — анимации нет вообще, сцена появляется сразу целиком.
 * FAST — прежний темп по умолчанию.
 * SLOW — вдвое медленнее FAST (новый темп по умолчанию).
 * Независимо от выбранной скорости (кроме INSTANT, где скипать нечего), тап по экрану
 * всегда может мгновенно завершить ТЕКУЩИЙ этап анимации — это не настройка, а всегда
 * доступная подсказка для нетерпеливых игроков.
 */
enum class RevealSpeed {
    INSTANT, FAST, SLOW;

    companion object {
        val DEFAULT = SLOW
    }
}
